// Inlines the TradingView Lightweight Charts standalone build (Apache-2.0) into the chart page so the chart
// works offline inside the Android WebView. Run automatically on `npm install` (postinstall).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = readFileSync(join(root, 'node_modules/lightweight-charts/dist/lightweight-charts.standalone.production.js'), 'utf8');
const version = JSON.parse(readFileSync(join(root, 'node_modules/lightweight-charts/package.json'), 'utf8')).version;
const template = readFileSync(join(root, 'scripts/chart-template.html'), 'utf8');
const html = template.replace('/*__LWC__*/', () => lib.replace(/<\/script>/gi, '<\\/script>'));
const out = join(root, 'src/components/chartHtml.generated.ts');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// AUTO-GENERATED by scripts/build-chart-html.mjs - do not edit.\n// Includes lightweight-charts ${version} (Apache-2.0, (c) TradingView, Inc.).\nexport const CHART_HTML: string = ${JSON.stringify(html)};\n`);
console.log(`chart html written (${Math.round(html.length / 1024)} KB, lightweight-charts ${version})`);
